    """Return every translation table merged into a single dict."""
    return Strings(
        types=TYPE_NAMES[code],
        damage_class=DAMAGE_CLASS[code],
        triggers=TRIGGERS[code],
        learn_methods=LEARN_METHODS[code],
        ui=UI[code],
    )
